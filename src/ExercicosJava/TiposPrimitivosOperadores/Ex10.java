package ExercicosJava.TiposPrimitivosOperadores;

public class Ex10 {
    public static void main(String[] args) {
        /*Crie um programa que declare três notas inteiras
        e exiba o resultado da média simples entre elas.*/

        int nota1 = 9;
        int nota2 = 8;
        int nota3 = 10;
        double media = (nota1 + nota2 + nota3) / 3.0;
        System.out.println("A média das notas é: " + media);

    }
}
